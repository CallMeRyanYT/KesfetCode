// Prepares the web game for over-the-air updates.
//
//   node scripts/build-update.mjs           (Vercel) stamp the version, zip the game,
//                                           and publish /app-update.json beside it
//   node scripts/build-update.mjs --no-zip  (Android CI) only stamp the version
//
// The version is a hash of the game's files, so a commit that changes nothing
// the children see never makes twenty tablets download an update.
import { createHash } from 'node:crypto';
import { readdir, readFile, writeFile, mkdir, rm } from 'node:fs/promises';
import { deflateRawSync } from 'node:zlib';
import { join, relative, resolve, sep } from 'node:path';
import { pathToFileURL } from 'node:url';

const ROOT = 'dist';
const UPDATE_DIR = 'app-update';
// Raise this (and tag a matching APK release) whenever the native Android
// shell changes in a way new web code depends on, such as a new plugin.
export const MIN_NATIVE_VERSION = '1.0.0';
const GENERATED = new Set(['build-info.js', 'app-update.json']);
const skip = path => path.startsWith(`${UPDATE_DIR}/`) || GENERATED.has(path) || path.endsWith('.prompt.txt');

async function files(dir = ROOT) {
  const out = [];
  for (const entry of await readdir(dir, { withFileTypes: true })) {
    const full = join(dir, entry.name);
    if (entry.isDirectory()) out.push(...await files(full));
    else out.push(relative(ROOT, full).split(sep).join('/'));
  }
  return out.filter(path => !skip(path)).sort();
}

export async function contentVersion(list) {
  const hash = createHash('sha256');
  for (const path of list) hash.update(path).update('\0').update(await readFile(join(ROOT, path))).update('\0');
  return hash.digest('hex').slice(0, 12);
}

// A minimal ZIP writer: no dependencies, so Vercel needs no npm install.
const CRC_TABLE = Array.from({ length: 256 }, (_, n) => {
  let c = n;
  for (let k = 0; k < 8; k++) c = c & 1 ? 0xedb88320 ^ (c >>> 1) : c >>> 1;
  return c >>> 0;
});
const crc32 = buffer => {
  let c = 0xffffffff;
  for (const byte of buffer) c = CRC_TABLE[(c ^ byte) & 0xff] ^ (c >>> 8);
  return (c ^ 0xffffffff) >>> 0;
};
const STORED = /\.(webp|png|jpe?g|glb|mp3|m4a|ogg|zip)$/i;

export function zip(entries) {
  const parts = [], central = [];
  let offset = 0;
  for (const { name, data } of entries) {
    const nameBytes = Buffer.from(name, 'utf8');
    const store = STORED.test(name);
    const body = store ? data : deflateRawSync(data, { level: 9 });
    const crc = crc32(data);
    const local = Buffer.alloc(30);
    local.writeUInt32LE(0x04034b50, 0); local.writeUInt16LE(20, 4); local.writeUInt16LE(0x0800, 6);
    local.writeUInt16LE(store ? 0 : 8, 8); local.writeUInt32LE(0, 10);
    local.writeUInt32LE(crc, 14); local.writeUInt32LE(body.length, 18); local.writeUInt32LE(data.length, 22);
    local.writeUInt16LE(nameBytes.length, 26); local.writeUInt16LE(0, 28);
    parts.push(local, nameBytes, body);
    const head = Buffer.alloc(46);
    head.writeUInt32LE(0x02014b50, 0); head.writeUInt16LE(20, 4); head.writeUInt16LE(20, 6); head.writeUInt16LE(0x0800, 8);
    head.writeUInt16LE(store ? 0 : 8, 10); head.writeUInt32LE(0, 12);
    head.writeUInt32LE(crc, 16); head.writeUInt32LE(body.length, 20); head.writeUInt32LE(data.length, 24);
    head.writeUInt16LE(nameBytes.length, 28); head.writeUInt32LE(offset, 42);
    central.push(head, nameBytes);
    offset += local.length + nameBytes.length + body.length;
  }
  const directory = Buffer.concat(central);
  const end = Buffer.alloc(22);
  end.writeUInt32LE(0x06054b50, 0); end.writeUInt16LE(entries.length, 8); end.writeUInt16LE(entries.length, 10);
  end.writeUInt32LE(directory.length, 12); end.writeUInt32LE(offset, 16);
  return Buffer.concat([...parts, directory, end]);
}

async function main() {
  const list = await files();
  const version = await contentVersion(list);
  const built = new Date().toISOString();
  await writeFile(join(ROOT, 'build-info.js'), `// Generated by scripts/build-update.mjs. Local builds report "dev".\nexport const BUILD = ${JSON.stringify({ version, built })};\n`);
  console.log(`Game version ${version} (${list.length} files).`);
  if (process.argv.includes('--no-zip')) return;

  await rm(join(ROOT, UPDATE_DIR), { recursive: true, force: true });
  await mkdir(join(ROOT, UPDATE_DIR), { recursive: true });
  const entries = [];
  for (const name of [...list, 'build-info.js'].sort()) entries.push({ name, data: await readFile(join(ROOT, name)) });
  const bundle = `${UPDATE_DIR}/kesfet-code-${version}.zip`;
  const archive = zip(entries);
  await writeFile(join(ROOT, bundle), archive);
  const manifest = {
    version, built,
    url: `/${bundle}`,
    size: archive.length,
    sha256: createHash('sha256').update(archive).digest('hex'),
    minNativeVersion: MIN_NATIVE_VERSION,
    apkUrl: 'https://github.com/CallMeRyanYT/KesfetCode/releases/latest'
  };
  await writeFile(join(ROOT, 'app-update.json'), JSON.stringify(manifest, null, 2));
  console.log(`Update bundle ${bundle}: ${(archive.length / 1e6).toFixed(1)} MB.`);
}

if (process.argv[1] && import.meta.url === pathToFileURL(resolve(process.argv[1])).href) {
  await main();
}
